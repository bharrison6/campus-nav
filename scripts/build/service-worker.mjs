// The site's service worker (decision mscn-v4-gps-offline-and-google-as-exit-only): emitted by the build as dist/sw.js
// with a precache manifest of every published file, so after the first visit the app, its data, the floor plans and
// the vector campus map work with no network.
//
//   precacheEntries(dir)                       -> [{url, hash, bytes}] for every file except the ones below
//   serviceWorkerSource({version, entries})    -> the sw.js text
//
// Not precached: sw.js itself, 404.html, CNAME, source maps, and the optional aerial tiles
// (data/campus-map/aerial/**), which are cached as they are seen, cache-first, capped at AERIAL_MAX_TILES.
// One generation per worker: a page this worker serves sees only this worker's build (page, version.json, campus
// data, floor plans, map manifest, outdoor graph, georef), so new indoor data never meets an old outdoor graph.
// Strategy in the worker:
//   navigations                 the precached index.html (cache-first; a new sw.js is the update signal)
//   data/version.json           the precached copy: the page asks for exactly this worker's data version
//   data/campus.json?v=X, floors/<id>.svg?v=X
//                               precache when X is the data version this worker was built with (or no ?v);
//                               any other X goes to the network only, never to this precache (which holds another
//                               version), so an old payload can never answer for a new version
//   data/campus-map/aerial/**   cache-first in its own capped cache
//   everything else precached   cache-first; anything else same-origin passes through to the network
// Updates: a changed build changes sw.js (BUILD below hashes the manifest; the browser checks sw.js on every
// navigation); the new worker installs its precache and waits, the running page keeps this build; the page offers
// "Updated, reload", which posts {type: 'skipWaiting'}; the new worker activates and every page it now controls
// reloads into the new build (WebApp_Main controllerchange). The worker does not claim pages it did not serve.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

export const AERIAL_MAX_TILES = 1200;
const SKIP = [/^sw\.js$/, /^404\.html$/, /^CNAME$/, /\.map$/, /^data\/campus-map\/aerial\//];

export function precacheEntries(dir) {
  const out = [];
  (function walk(d) {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) { walk(p); continue; }
      const url = relative(dir, p).split(sep).join('/');
      if (SKIP.some((re) => re.test(url))) continue;
      const body = readFileSync(p);
      out.push({ url, hash: createHash('sha256').update(body).digest('hex').slice(0, 12), bytes: body.length });
    }
  })(dir);
  return out;
}

export function buildHash(entries) {
  return createHash('sha256').update(entries.map((e) => e.url + ' ' + e.hash).join('\n')).digest('hex').slice(0, 12);
}

export function serviceWorkerSource({ version, entries }) {
  const build = buildHash(entries);
  const files = entries.map((e) => e.url);
  return `/* Murray State Campus Nav service worker. Generated by scripts/build/service-worker.mjs; do not edit. */
/* build ${build}, data ${String(version)}, ${files.length} files, ${entries.reduce((n, e) => n + e.bytes, 0)} bytes */
var BUILD = ${JSON.stringify(build)};
var DATA_VERSION = ${JSON.stringify(String(version))};
var PRECACHE = 'mscn-precache-' + BUILD;
var AERIAL = 'mscn-aerial-v1';
var AERIAL_MAX = ${AERIAL_MAX_TILES};
var FILES = ${JSON.stringify(entries.map((e) => [e.url, e.hash]))};

function scopeUrl(path) { return new URL(path, self.registration.scope).href; }

self.addEventListener('install', function (event) {
  event.waitUntil(caches.open(PRECACHE).then(function (cache) {
    return cache.addAll(FILES.map(function (f) { return new Request(scopeUrl(f[0]), { cache: 'reload' }); }));
  }));
});

self.addEventListener('activate', function (event) {
  event.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf('mscn-precache-') === 0 && k !== PRECACHE; })
      .map(function (k) { return caches.delete(k); }));
  }));
});

self.addEventListener('message', function (event) {
  if (event.data && event.data.type === 'skipWaiting') { self.skipWaiting(); }
  if (event.data && event.data.type === 'version' && event.ports && event.ports[0]) {
    event.ports[0].postMessage({ build: BUILD, data: DATA_VERSION, files: FILES.length });
  }
});

function fromPrecache(request) {
  return caches.open(PRECACHE).then(function (cache) { return cache.match(request, { ignoreSearch: true }); });
}

function cacheFirst(request) {
  return fromPrecache(request).then(function (hit) { return hit || fetch(request); });
}


function trimAerial(cache) {
  return cache.keys().then(function (keys) {
    var extra = keys.length - AERIAL_MAX;
    var dels = [];
    for (var i = 0; i < extra; i++) { dels.push(cache.delete(keys[i])); }
    return Promise.all(dels);
  });
}

function aerialTile(request) {
  return caches.open(AERIAL).then(function (cache) {
    return cache.match(request).then(function (hit) {
      if (hit) { return hit; }
      return fetch(request).then(function (res) {
        if (res && res.ok) { cache.put(request, res.clone()).then(function () { return trimAerial(cache); }); }
        return res;
      });
    });
  });
}

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') { return; }
  var url = new URL(req.url);
  var scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || url.pathname.indexOf(scope.pathname) !== 0) { return; }
  var path = url.pathname.slice(scope.pathname.length);
  if (req.mode === 'navigate') {
    event.respondWith(fromPrecache(new Request(scopeUrl('index.html'))).then(function (hit) { return hit || fetch(req); }));
    return;
  }
  if (path.indexOf('data/campus-map/aerial/') === 0) { event.respondWith(aerialTile(req)); return; }
  if (path === 'data/campus.json' || /^floors\\/[^/]+\\.svg$/.test(path)) {
    var v = url.searchParams.get('v');
    event.respondWith(v && v !== DATA_VERSION ? fetch(req) : cacheFirst(req));
    return;
  }
  event.respondWith(cacheFirst(req));
});
`;
}
